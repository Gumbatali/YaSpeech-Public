/**
 * Отсортированный по убыванию длины список для безопасного построчного
 * применения regex-замен (длинные фразы обрабатываются раньше коротких).
 */
export const FILLER_WORDS = [...new Set(RAW_FILLERS)].sort((a, b) => b.length - a.length);

/**
 * Экранирует спецсимволы regex в строке филлера.
 */
function escapeRegex(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Собираем один составной regex вместо цикла из полусотни regex — быстрее
// и не даёт частичным заменам сдвигать индексы друг друга непредсказуемо.
//
// ВАЖНО: \b в JS regex определяется через \w, а \w НЕ включает кириллицу —
// "\bда\b" никогда не совпадёт с русским "да" (граница слова просто не
// возникает вокруг кириллических букв). Поэтому границы задаём вручную через
// lookaround на "не-букву" (включая начало/конец строки), а не \b.
const NON_LETTER_BEHIND = "(?<=^|[^a-zа-яё])";
const NON_LETTER_AHEAD = "(?=[^a-zа-яё]|$)";

const FILLER_PATTERN = new RegExp(
  FILLER_WORDS
    .map((f) => {
      const escaped = escapeRegex(f);
      // Записи, начинающиеся с "-" ("-то", "-ка") клеятся к предыдущему
      // слову без разделителя — левую границу не требуем.
      const left = f.startsWith("-") ? "" : NON_LETTER_BEHIND;
      // Записи, уже оканчивающиеся на запятую, сами несут правую границу.
      const right = /[,]$/.test(f) ? "" : NON_LETTER_AHEAD;
      return `${left}${escaped}${right}`;
    })
    .join("|"),
  "gi"
);

/**
 * Удаляет слова-паразиты и дискурсивные маркеры ИЗ ЛЮБОГО МЕСТА текста —
 * не только целых коротких сегментов-реакций, но и подстрок внутри длинной
 * непрерывной реплики ("да, да, это в начале у эээ меня на прошлой неделе").
 *
 * Не трогает числа, даты, термины — список полностью состоит из
 * общеупотребимых заполнителей, не пересекающихся с содержательной лексикой.
 */
export function removeFillerWords(text) {
  if (!text) return "";
  return text
    .replace(FILLER_PATTERN, "")
    .replace(/\s+/g, " ")
    .replace(/\s+([,.!?])/g, "$1") // пробел перед знаком препинания, оставшийся после удаления
    .replace(/([,.!?])\1+/g, "$1") // задвоенные знаки препинания после удаления слова между ними
    .trim();
}

// Слова, для которых повтор подряд ("да, да, да") почти всегда — заикание/
// эхо самого говорящего перед основной мыслью, а не два разных содержательных
// употребления. НЕ включает обычную лексику ("второе, второе" — это могут
// быть два РАЗНЫХ упоминания, например "на второе[число]... второе[он] не
// берёт трубку" — схлопывать такое означает тихо терять смысл фразы).
const REPEATABLE_REACTIONS = new Set([
  "да", "нет", "ну", "так", "угу", "ага", "хорошо", "понял", "ясно",
  "конечно", "точно", "именно", "верно"
]);

const REPEATABLE_PATTERN = [...REPEATABLE_REACTIONS]
  .sort((a, b) => b.length - a.length)
  .map(escapeRegex)
  .join("|");

/**
 * Схлопывает подряд идущие повторы одного и того же слова-реакции:
 * "да, да, да, конечно" → "да, конечно". ASR часто дублирует такое слово
 * при заикании или паузе говорящего перед основной мыслью.
 *
 * Намеренно ограничено списком REPEATABLE_REACTIONS, а не любым словом —
 * для произвольной лексики регулярка не может отличить заикание одного
 * повторённого слова от двух РАЗНЫХ содержательных употреблений того же
 * слова в соседних клаузах ("второе, второе не берёт трубку" — оба "второе"
 * значимы, схлопывание тихо теряет смысл).
 */
export function collapseRepeatedWords(text) {
  if (!text) return "";
  // \b не годится для кириллицы (см. комментарий у FILLER_PATTERN) — граница
  // слова через lookaround на "не-букву" вместо встроенного \w-based \b.
  const re = new RegExp(
    `(?<=^|[^a-zа-яё])(${REPEATABLE_PATTERN})(?=[^a-zа-яё]|$)(?:[,\\s]+\\1(?=[^a-zа-яё]|$))+`,
    "gi"
  );
  return text.replace(re, "$1");
}
