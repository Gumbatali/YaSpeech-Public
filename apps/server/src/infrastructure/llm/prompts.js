/**
 * Шаблоны промтов для многопроходного анализа транскрипта.
 *
 * Техники:
 *   - Few-shot примеры — модель видит образец "правильного" ответа
 *   - Chain-of-thought в system prompt — явная инструкция думать последовательно
 *   - Negative constraints — явный запрет выдумывать
 *   - Uncertainty markers — [?слово?] для плохо распознанных фрагментов
 *   - Structured JSON output — строгая схема ответа
 *   - Role-based framing — GPT получает конкретную профессиональную роль
 */

// ============================================================
// PASS A1: GPT-диаризация (только для mono-транскриптов)
// ============================================================
export function promptDiarization({ transcriptText, domain, mentionedPeople = [] }) {
  const peopleHint = mentionedPeople.length
    ? `В тексте упоминаются имена: ${mentionedPeople.join(", ")} — используй как подсказку для атрибуции реплик.`
    : "";

  const system = `Ты — эксперт по анализу деловых переговоров в сфере "${domain}".
Получаешь сплошной текст расшифровки — система распознавания речи не смогла разделить спикеров.

ЗАДАЧА: Разбить текст на реплики по спикерам.

КАК ОПРЕДЕЛЯТЬ СМЕНУ СПИКЕРА:
1. Вопрос → ответ: смена происходит между вопросом и ответом
2. Обращение по имени: "Роман, ты..." — значит до этого говорил другой
3. Слова согласия/ответа в начале реплики: "Да", "Нет", "Хорошо", "Понял", "Угу" — скорее всего другой спикер
4. Резкая смена темы или точки зрения
5. Смена лица: "мы сделаем" → "ты сделай" → "я уже сделал"

ПРАВИЛА:
- Минимум 2, максимум 6 спикеров
- Не дроби слишком мелко — реплика минимум 3-5 слов, кроме коротких ответов
- Если неясно кто говорит — оставь за предыдущим спикером
- НЕ добавляй и НЕ удаляй слова из оригинала, только переносишь в атрибуцию
- Нумеруй: Спикер 1, Спикер 2, ...
- Отвечай только JSON без пояснений`;

  const user = `Сфера: "${domain}".
${peopleHint}

Текст расшифровки (без разметки спикеров):
${transcriptText}

Верни JSON:
{
  "speakers": 2,
  "segments": [
    { "speaker": "Спикер 1", "text": "завтра надо сдать документы по объекту" },
    { "speaker": "Спикер 2", "text": "хорошо, сделаю до обеда" }
  ]
}`;

  return { system, user, options: { temperature: 0.2, maxTokens: 8000 } };
}

// ============================================================
// PASS A2: Коррекция ASR-ошибок (на чанке)
// ============================================================
export function promptAsrCorrection({ chunkText, domain, chunkIndex, totalChunks, glossary = null }) {
  const glossaryBlock = glossary?.terms?.length
    ? `\nГЛОССАРИЙ ПРЕДМЕТНОЙ ОБЛАСТИ (используй при восстановлении слов):
${glossary.terms.map((t) => `  "${t.variants.join(" / ")}" → "${t.term}"`).join("\n")}
${Object.entries(glossary.abbreviations || {}).map(([k, v]) => `  "${k}" = ${v}`).join("\n")}\n`
    : "";

  const system = `Ты — опытный редактор записей деловых переговоров в сфере "${domain}".
Получаешь фрагмент транскрипта, полученного автоматическим распознаванием речи (ASR).
ASR часто грубо искажает слова: вместо "исполнительная документация" может написать "исполнение документация", вместо "техническое обследование" — "технической освидетельствование". Это нормально.

ЗАДАЧА: Восстановить смысл каждой реплики, исправив ошибки ASR.

ПРИНЦИПЫ РАБОТЫ:

1. ЧИТАЙ КОНТЕКСТ, НЕ СЛОВА.
   Смотри на всю реплику целиком и на соседние реплики. Вопрос "кто контролирует мониторинг?"
   не может получить ответ "зубное смещенное вырезание" — значит ASR сильно ошибся,
   восстанови логичный ответ на основе темы разговора.

2. УРОВНИ КОРРЕКЦИИ (применяй нужный):
   - Лёгкая: "исполниловка" → "исполнительная документация", "техобследование" → "техническое обследование"
   - Средняя: "сомафорка мышцы глюкоза" в деловом разговоре о строительстве → скорее всего искажённый
     строительный термин или название — пометь [?...?] но попробуй угадать из контекста
   - Тяжёлая: бессмысленный набор слов, не связанный с темой → кратко восстанови смысл
     исходя из контекста реплики, добавь пометку [восст.]

3. ПРИОРИТЕТЫ ПРИ ВОССТАНОВЛЕНИИ:
   а) Используй глоссарий (если дан)
   б) Используй тему разговора (строительство → документация, сроки, объекты, согласования)
   в) Используй логику диалога (вопрос требует ответа, команда — подтверждения)
   г) Не оставляй явную бессмыслицу — лучше [?что-то о документах?] чем "зубное вырезание"

4. ФОРМАТ:
   - Сохраняй "Спикер N:" префиксы точно как в исходнике
   - Реплики из одних звуков ("эм", "угу", "ну") — удаляй
   - Отвечай только JSON без пояснений
${glossaryBlock}
ПРИМЕР (строительство):
ВВОД:  Спикер 1: зубное смещенное вырезание нет не знаю почему
ВЫВОД: Спикер 1: [?дюбельное смещение?] нет, не знаю почему

ВВОД:  Спикер 2: сомафорка мышцы глюкоза
ВЫВОД: Спикер 2: [восст. — неразборчиво, возможно о материалах или оборудовании]

ВВОД:  Спикер 1: исполнительная дока согласована с заказчиком
ВЫВОД: Спикер 1: исполнительная документация согласована с заказчиком`;

  const user = `Фрагмент ${chunkIndex + 1} из ${totalChunks}. Сфера: "${domain}".

${chunkText}

Верни JSON: { "correctedLines": ["Спикер N: текст", ...] }`;

  return { system, user, options: { temperature: 0.25, maxTokens: 2500 } };
}

