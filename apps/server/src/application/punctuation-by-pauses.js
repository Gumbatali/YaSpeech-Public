/**
 * Восстановление пунктуации в сыром ASR-тексте по длине пауз между словами —
 * без LLM, детерминированно.
 *
 * SpeechKit v3 отдаёт временные метки на уровне каждого слова (startTimeMs/
 * endTimeMs), но раньше этот код их отбрасывал и использовал только для
 * границ всей фразы. Пауза между речью — сильный просодический признак
 * границы предложения/клаузы: длинная пауза почти всегда значит конец мысли,
 * короткая — естественный вдох или перечисление внутри одной мысли.
 *
 * Пороги ниже не универсальная константа "правильной" длины паузы — это
 * практическая калибровка, применяемая в схожих задачах (см. эвристики
 * whisperX/stable-ts для расстановки границ сегментов по паузам): точка от
 * ~0.5с, запятая от ~0.2с. Подбор адаптивного порога под темп речи конкретного
 * спикера — сознательно оставлен как TODO ниже, а не имплементирован сразу:
 * фиксированный порог уже даёт ощутимое улучшение и его проще тестировать.
 */

// Калибровано на реальной записи (19 минут, деловая планёрка, 2 спикера).
// ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ (не баг, фундаментальное свойство чисто просодического
// подхода): на неидеально артикулированной речи говорящий иногда делает
// долгую паузу ПОСЕРЕДИ словосочетания — подбирает следующее слово, запинается
// — и это по длительности неотличимо от паузы на границе предложения. Пример
// из этой же записи: "перед [пауза 1820мс] праздниками" — разрыв внутри
// словосочетания, потому что пауза реально длинная, а не потому что порог
// подобран неверно. Подняв порог, эту категорию ошибок не убрать — она не
// про калибровку числа, а про то, что длина паузы не всегда коррелирует с
// синтаксической границей на реальной речи. Решение просодией без LLM
// принимает эту погрешность как компромисс; если критично важна точность
// границ предложений — нужен LLM- или ML-проход (см. REFINE, пункт 4
// "расставь пунктуацию" в prompts.js), а не более тонкая настройка порога.
const SENTENCE_PAUSE_MS = 900;
const COMMA_PAUSE_MS = 350;

// Союзы/частицы, перед которыми запятая нужна почти всегда независимо от
// паузы (SpeechKit часто не делает паузу перед ними, диктующий говорит слитно).
const COMMA_BEFORE = new Set([
  "потому", "который", "которая", "которое", "которые",
  "если", "чтобы", "хотя", "когда", "поэтому", "который",
  "но", "однако", "значит", "соответственно"
]);

/**
 * Расставляет точки и запятые в тексте фразы на основе пауз между словами.
 * НЕ меняет сами слова — только добавляет знаки препинания между ними и
 * капитализирует первую букву после точки. Не трогает текст, если слова
 * с таймингами недоступны (fallback — текст остаётся как есть, следующий
 * REFINE-проход при необходимости расставит пунктуацию через LLM).
 *
 * @param {Array<{text: string, startTimeMs: number, endTimeMs: number}>} words
 * @returns {string}
 */
export function punctuateByPauses(words) {
  if (!Array.isArray(words) || words.length === 0) return "";

  const parts = [];
  let capitalizeNext = true;

  for (let i = 0; i < words.length; i++) {
    const word = words[i]?.text?.trim();
    if (!word) continue;

    let piece = word;
    if (capitalizeNext) {
      piece = piece.charAt(0).toUpperCase() + piece.slice(1);
      capitalizeNext = false;
    }
    parts.push(piece);

    const next = words[i + 1];
    if (!next) continue;

    const pauseMs = (next.startTimeMs ?? 0) - (words[i].endTimeMs ?? 0);
    const nextWordLower = (next.text ?? "").trim().toLowerCase();

    if (pauseMs >= SENTENCE_PAUSE_MS) {
      parts.push(".");
      capitalizeNext = true;
    } else if (pauseMs >= COMMA_PAUSE_MS || COMMA_BEFORE.has(nextWordLower)) {
      parts.push(",");
    }
  }

  let result = parts.join(" ")
    .replace(/\s+([,.])/g, "$1") // убрать пробел перед знаком препинания
    .trim();

  if (result && !/[.!?]$/.test(result)) {
    result += ".";
  }

  return result;
}

