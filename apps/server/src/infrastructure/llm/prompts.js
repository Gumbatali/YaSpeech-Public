// PASS C1: Извлечение протокола
// ============================================================
export function promptProtocolExtraction({
  transcriptText,
  domain,
  meetingType,
  mainTopics,
  speakerMap,
  prevActionItems,
  meetingDate,
  projectName,
  organizations
}) {
  const prevSection = prevActionItems?.length
    ? `\nЗадачи с предыдущей встречи (определи статус по транскрипту):
${prevActionItems.map((a) => `- [${a.owner}] ${a.task} (дедлайн: ${a.deadline})`).join("\n")}`
    : "";

  const system = `Ты — профессиональный секретарь деловых встреч. Работаешь в сфере "${domain}".
Дата встречи: ${meetingDate}. Тип: ${meetingType}.

ПРАВИЛА (строго):
1. "decisions" — ТОЛЬКО реально принятые решения. Признаки: "решили", "утвердили", "договорились". Если таких нет — пустой массив [].
2. "actionItems" — ТОЛЬКО конкретные задачи с ответственным лицом. Ответственный не назван → "Команда". Дедлайн не назван → +2 недели от даты встречи.
3. НЕ ВЫДУМЫВАЙ. Если информация не подтверждается транскриптом — пустой массив или null. Выдумка хуже пустого поля.
4. "openQuestions" — вопросы которые ОБСУЖДАЛИ но НЕ РЕШИЛИ.
5. "transcriptHighlights" — 3-5 самых ценных высказываний (не приветствия, не "угу"). Только если можно точно процитировать из текста.
6. summary.title — отражает РЕАЛЬНУЮ тему разговора из транскрипта, не придумывай.
7. Игнорируй явные ASR-артефакты: случайные слова, "окей гугл", "алиса", непонятные звуки.
8. Если транскрипт слишком плохого качества для извлечения данных — верни summary с описанием проблемы и пустые массивы для остальных полей.
9. Отвечай только корректным JSON.
10. summary.overview — деловой русский язык. Используй активный залог и именные сказуемые: «Участники обсудили…», «Команда согласовала…», «Стороны договорились…». Следи за падежным управлением: «договорились о сроках», «согласовали конструктивное решение», «выявили проблемы с документацией». Не используй пассивные безличные конструкции вроде «было принято решение», «обсуждались вопросы». Числа и единицы согласовывай с существительными.`;

  const user = `Проект: "${projectName}"
Сфера: ${domain} / тип: ${meetingType}
Темы: ${mainTopics.join(", ")}
Организации: ${organizations.join(", ") || "—"}

Спикеры:
${speakerMap}
${prevSection}

Транскрипт:
${transcriptText.slice(0, 22_000)}

⚠️ ВАЖНО: Ниже — ТОЛЬКО ФОРМАТ ОТВЕТА. Не копируй плейсхолдеры. Заполни ИСКЛЮЧИТЕЛЬНО тем, что есть в транскрипте выше.
Если информации нет — ставь пустой массив [] или null. Лучше пусто, чем выдумано.

Верни JSON строго по этому формату:
{
  "summary": {
    "title": "<конкретный заголовок из содержания встречи, 5-10 слов>",
    "overview": "<4-6 предложений деловой прозы: что обсудили, к чему пришли, что осталось открытым. Активный залог, именные сказуемые, правильное падежное управление>"
  },
  "participants": ["<имя из транскрипта>"],
  "decisions": [
    "<решение дословно из транскрипта>"
  ],
  "actionItems": [
    { "owner": "<ответственный из транскрипта>", "task": "<задача из транскрипта>", "deadline": "<дата или null>" }
  ],
  "completedFromPrevious": [],
  "carriedForward": [],
  "openQuestions": [
    "<вопрос который обсуждали но не решили>"
  ],
  "transcriptHighlights": [
    { "speaker": "<спикер>", "quote": "<дословная цитата из транскрипта>" }
  ]
}`;

  return { system, user, options: { temperature: 0.15, maxTokens: 4000 } };
}

