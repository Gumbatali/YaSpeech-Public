/**
 * Шаблоны промтов для многопроходного анализа транскрипта.
 *
 * Техники:
 *   - Few-shot примеры — модель видит образец "правильного" ответа
 *   - Chain-of-thought в system prompt — явная инструкция думать последовательно
 *   - Negative constraints — явный запрет выдумывать
 *   - Uncertainty markers — [?слово?] для плохо распознанных фрагментов
 *   - Structured JSON output — строгая схема ответа
 *   - Role-based framing — GPT получает конкретную профессиональную роль
 */

// ============================================================
// PASS A1: GPT-диаризация (только для mono-транскриптов)
// ============================================================
export function promptDiarization({ transcriptText, domain, mentionedPeople = [] }) {
  const peopleHint = mentionedPeople.length
    ? `В тексте упоминаются имена: ${mentionedPeople.join(", ")} — используй как подсказку для атрибуции реплик.`
    : "";

  const system = `Ты — эксперт по анализу деловых переговоров в сфере "${domain}".
Получаешь сплошной текст расшифровки — система распознавания речи не смогла разделить спикеров.

ЗАДАЧА: Разбить текст на реплики по спикерам.

КАК ОПРЕДЕЛЯТЬ СМЕНУ СПИКЕРА:
1. Вопрос → ответ: смена происходит между вопросом и ответом
2. Обращение по имени: "Роман, ты..." — значит до этого говорил другой
3. Слова согласия/ответа в начале реплики: "Да", "Нет", "Хорошо", "Понял", "Угу" — скорее всего другой спикер
4. Резкая смена темы или точки зрения
5. Смена лица: "мы сделаем" → "ты сделай" → "я уже сделал"

ПРАВИЛА:
- Минимум 2, максимум 6 спикеров
- ВАЖНО: не слипай всех в двоих по умолчанию. Если есть признаки третьего и более
  участников (новые обращения по имени, разные роли, реплики которые не вписываются
  в диалог двоих) — выделяй 3, 4 и более спикеров. Совещания часто ведут 3-5 человек.
- Не дроби слишком мелко — реплика минимум 3-5 слов, кроме коротких ответов
- Если неясно кто говорит — оставь за предыдущим спикером
- НЕ добавляй и НЕ удаляй слова из оригинала, только переносишь в атрибуцию
- Нумеруй: Спикер 1, Спикер 2, ...
- Отвечай только JSON без пояснений`;

  const user = `Сфера: "${domain}".
${peopleHint}

Текст расшифровки (без разметки спикеров):
${transcriptText}

Пример на 3 спикера (участников может быть больше двух):
{
  "speakers": 3,
  "segments": [
    { "speaker": "Спикер 1", "text": "коллеги, начнём с объекта на ленина" },
    { "speaker": "Спикер 2", "text": "по фундаменту всё готово, бетон принят" },
    { "speaker": "Спикер 3", "text": "а у меня вопрос по срокам поставки арматуры" }
  ]
}

Верни JSON в таком же формате (speakers — реальное число спикеров, которое ты определил).`;

  return { system, user, options: { temperature: 0.2, maxTokens: 8000 } };
}

// ============================================================
// PASS A1b: GPT-диаризация по составу проекта (кнопка «Разметить аудио с ИИ»)
//
// В отличие от promptDiarization (только mono-фоллбэк, число спикеров
// угадывается по тексту), здесь заранее известен состав участников встречи —
// команда проекта + гости. Это сильная подсказка модели: не "определи,
// сколько человек говорит", а "раздели текст между ЭТИМИ конкретными людьми".
// Работает даже если SpeechKit уже разделил на speaker-1/2 — в реальных
// записях диаризация SpeechKit часто ошибается (перегородки, шум, один канал),
// поэтому разметка по составу проекта запускается ВСЕГДА, а не только для mono.
// ============================================================
export function promptDiarizationByTeam({ transcriptText, domain, participants, contextTail = null }) {
  const namesList = participants.length
    ? participants.map((p, i) => `${i + 1}. ${p}`).join("\n")
    : null;

  const participantsBlock = namesList
    ? `УЧАСТНИКИ ВСТРЕЧИ (известный состав, из карточки проекта):\n${namesList}\n\n` +
      `Ожидаемое число говорящих: ${participants.length}. Это подсказка, а не жёсткое ограничение — ` +
      `если из текста очевидно, что реально говорящих меньше (кто-то не проронил ни слова) ` +
      `или больше (незапланированный гость), доверяй содержанию текста.`
    : `Состав участников неизвестен — определи число говорящих по содержанию текста.`;

  const contextBlock = contextTail
    ? `\nКОНЕЦ ПРЕДЫДУЩЕГО ФРАГМЕНТА (уже размечен, НЕ включай в ответ, только для согласования нумерации спикеров):\n${contextTail}\n`
    : "";

  const system = `Ты — эксперт по анализу деловых переговоров в сфере "${domain}".
Получаешь текст расшифровки записи (возможно, фрагмент длинной записи). Твоя задача —
разбить его на РЕПЛИКИ ПО ПРЕДЛОЖЕНИЯМ/МЫСЛЯМ и приписать каждую конкретному спикеру,
опираясь на известный состав участников встречи.

КАК ОПРЕДЕЛЯТЬ СМЕНУ СПИКЕРА:
1. Вопрос → ответ: смена происходит между вопросом и ответом
2. Обращение по имени: "Роман, ты..." — значит до этого говорил другой (и упомянутый — вероятный кандидат)
3. Слова согласия/ответа в начале реплики: "Да", "Нет", "Хорошо", "Понял", "Угу" — скорее всего другой спикер
4. Резкая смена темы, роли или точки зрения (руководитель формулирует задачу → исполнитель отчитывается)
5. Смена лица: "мы сделаем" → "ты сделай" → "я уже сделал"

ВАЖНО ПРО ГРАНУЛЯРНОСТЬ:
- Не объединяй весь фрагмент в 1-2 гигантские реплики "для простоты" — это неприемлемо.
  Ожидается МНОГО отдельных реплик (диалог с частой сменой говорящего — норма для совещаний).
- Одна реплика = один непрерывный отрезок речи ОДНОГО человека, обычно 1-4 предложения.
  Как только тема/мысль/говорящий меняется — новая реплика, даже внутри одного длинного фрагмента.
- Если сомневаешься — дроби МЕЛЬЧЕ, а не крупнее: пропущенная смена спикера хуже, чем лишняя реплика.

ОСТАЛЬНЫЕ ПРАВИЛА:
- Используй известный состав участников как ориентир по числу говорящих, но не выдумывай
  реплики людям, которые явно не участвовали в разговоре (судя по тексту).
- Не дроби короткие реакции ("да", "угу") отдельно от их непосредственного контекста без причины.
- Если неясно кто говорит — оставь за предыдущим спикером.
- НЕ добавляй и НЕ удаляй слова из оригинала, только переносишь в атрибуцию.
- Нумеруй спикеров: Спикер 1, Спикер 2, ... (не имена — имена подставятся позже отдельным шагом).
  Если дан контекст предыдущего фрагмента — сохраняй ТЕ ЖЕ номера для тех же людей.
- Отвечай только JSON без пояснений.`;

  const user = `Сфера: "${domain}".

${participantsBlock}
${contextBlock}
Текст расшифровки${contextTail ? " (продолжение)" : ""}:
${transcriptText}

Пример ответа на 3 спикера:
{
  "speakers": 3,
  "segments": [
    { "speaker": "Спикер 1", "text": "коллеги, начнём с объекта на ленина" },
    { "speaker": "Спикер 2", "text": "по фундаменту всё готово, бетон принят" },
    { "speaker": "Спикер 3", "text": "а у меня вопрос по срокам поставки арматуры" }
  ]
}

Верни JSON в таком же формате (speakers — реальное число спикеров, которое ты определил по тексту).`;

  return { system, user, options: { temperature: 0.2, maxTokens: 8000 } };
}

