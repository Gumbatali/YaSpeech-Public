// REDUCE: консолидация частичных протоколов (map-reduce, длинные встречи)
// ============================================================
export function promptProtocolReduce({ merged, meetingDate, projectName, domain }) {
  const system = `Ты — профессиональный секретарь деловых встреч (сфера: "${domain}").
Получаешь черновой протокол, собранный из нескольких фрагментов одной длинной встречи.
Из-за пофрагментной обработки в нём есть дубли и рваная сводка.

ЗАДАЧА: консолидировать протокол.
ПРАВИЛА:
1. Убери дубли решений и задач (одно и то же может быть сформулировано по-разному).
2. summary.overview перепиши как цельную сводку всей встречи (4-6 предложений, активный залог).
3. НЕ добавляй ничего нового — только то, что уже есть в черновике.
4. Сохрани структуру JSON в точности.
5. Отвечай только корректным JSON.`;

  const user = `Проект: "${projectName}". Дата встречи: ${meetingDate}.

Черновой протокол:
${JSON.stringify(merged, null, 2).slice(0, 24_000)}

Верни консолидированный протокол в том же JSON-формате.`;

  return { system, user, options: { temperature: 0.15, maxTokens: 4000 } };
}

// ============================================================
// REFINE: LLM-коррекция расшифровки по line-ID-протоколу
// (промпт проверен бенчмарком scripts/experiments/llm-refine-bench:
//  WER 18.4% → 6.8% на Lite, 100% format compliance)
// ============================================================
export function promptTranscriptRefine({ numberedLines, contextLines = [], domain, glossary = null }) {
  const glossaryBlock = glossary?.terms?.length
    ? `\nГЛОССАРИЙ ПРЕДМЕТНОЙ ОБЛАСТИ (используй при восстановлении слов):
${glossary.terms.map((t) => `  "${(t.variants ?? []).join(" / ")}" → "${t.term}"`).join("\n")}
${Object.entries(glossary.abbreviations || {}).map(([k, v]) => `  "${k}" = ${v}`).join("\n")}\n`
    : "";

  const contextBlock = contextLines.length
    ? `\nКОНТЕКСТ (предыдущие реплики, НЕ исправлять, НЕ включать в ответ):
${contextLines.join("\n")}\n`
    : "";

  const system = `Ты — опытный редактор записей деловых переговоров в сфере "${domain}".
Получаешь пронумерованные реплики транскрипта, полученного автоматическим распознаванием речи (ASR).
ASR часто искажает слова: разрывает их ("гидра изоляция" = "гидроизоляция"), пишет числа и аббревиатуры словами ("ка эс два" = "КС-2", "а пятьсот эс" = "А500С"), грубо путает термины.

ЗАДАЧА: исправить ошибки ASR в каждой реплике, восстановив смысл.

ПРАВИЛА:
1. Читай контекст всего разговора, а не отдельные слова.
2. Склеивай разорванные слова, восстанавливай искажённые термины. Профессиональный сленг раскрывай в полную форму ("исполниловка" → "исполнительная документация").
3. Марки, аббревиатуры и обозначения записывай в технической форме: "м триста пятьдесят" → "М350", "ка эс два" → "КС-2". Обычные числительные оставляй словами, как произнесены ("двести" остаётся "двести"). НИКОГДА не меняй сами числа, даты и суммы.
4. Расставь пунктуацию и заглавные буквы.
5. НЕ добавляй ничего, чего не было сказано. НЕ удаляй и НЕ сокращай сказанное — каждое слово исходной реплики должно сохраниться или быть исправлено, выбрасывать слова запрещено. НЕ перефразируй верный текст.
6. Если фрагмент — бессмыслица, не связанная с контекстом, попробуй восстановить термин из контекста; если невозможно — пометь [?...?].
7. Формат ответа — СТРОГО построчно, без пояснений, без JSON:
[номер] исправленный текст реплики
8. Сохрани все номера. Каждая входная реплика = ровно одна строка ответа с тем же номером. Префикс "Спикер N:" в ответ НЕ включай.
${glossaryBlock}`;

  const user = `${contextBlock}Реплики:
${numberedLines.join("\n")}

Верни исправленные реплики построчно в формате [номер] текст.`;

  // Выход ≈ вход; +30% запас на пунктуацию и раскрытие сокращений
  const inputChars = numberedLines.reduce((s, l) => s + l.length, 0);
  const maxTokens = Math.min(8000, Math.max(1000, Math.ceil((inputChars / 2.5) * 1.3)));

  return { system, user, options: { temperature: 0.25, maxTokens } };
}

// ============================================================
// DIALOGUE: литературная запись реплик (проход "Диалог", после REFINE)
//
// Отдельно от REFINE намеренно: REFINE — точная реставрация слов/терминов
// с запретом что-либо выбрасывать (используется как источник правды для
// протокола). DIALOGUE берёт уже исправленный текст и убирает слова-паразиты,
// склеивает рваные фразы — читаемость важнее дословности. Формат ответа и
// line-ID-протокол те же (parseRefinedLines), защита от подмены фактов —
// applyDialogueLines (числа + порог длины, см. refiner.js).
// ============================================================
export function promptDialogueRewrite({ numberedLines, contextLines = [], domain, glossary = null }) {
  const glossaryBlock = glossary?.terms?.length
    ? `\nГЛОССАРИЙ ПРЕДМЕТНОЙ ОБЛАСТИ (пиши термины в этом написании):
${glossary.terms.map((t) => `  "${t.term}"`).join("\n")}\n`
    : "";

  const contextBlock = contextLines.length
    ? `\nКОНТЕКСТ (предыдущие реплики, НЕ переписывать, НЕ включать в ответ):
${contextLines.join("\n")}\n`
    : "";

  const system = `Ты — литературный редактор расшифровок деловых встреч в сфере "${domain}".
Получаешь пронумерованные реплики — текст УЖЕ очищен от ошибок распознавания речи,
термины и числа в нём верны. Твоя задача — сделать реплики читаемыми, как в хорошей
статье-интервью: живая речь без мусора, а не протокольный канцелярит.

ЧТО УБИРАТЬ:
- слова-паразиты и заполнители: "ну", "вот", "короче", "типа", "как бы", "в общем-то", "значит"
- самоперебивы и фальстарты: "я хотел... то есть я думаю" → "я думаю"
- дословные повторы: "нужно, нужно сделать" → "нужно сделать"
- междометия без смысловой нагрузки: "эээ", "ммм", "так сказать"

ЧТО СОХРАНЯТЬ ОБЯЗАТЕЛЬНО:
1. Все факты: числа, даты, суммы, адреса, названия, имена — БЕЗ ИЗМЕНЕНИЙ, даже на один символ.
2. Все содержательные утверждения и решения — ничего не пересказывай короче, не обобщай,
   не выбрасывай мысль целиком. Убираешь мусор вокруг мысли, а не саму мысль.
3. Разговорный голос от первого лица — не превращай прямую речь в протокольный стиль
   ("я думаю, что кс три готов", а не "докладываю о готовности КС-3").
4. Короткие реплики-реакции ("да", "согласен", "хорошо", "понял") оставляй короткими —
   не раздувай их до полноценных предложений.
5. Если реплика — набор слов без связи с контекстом (артефакт распознавания), оставь как есть,
   не пытайся сочинить связный текст вместо неё.

ЗАПРЕЩЕНО:
- добавлять любую информацию, которой не было в реплике
- менять числа, даты, имена собственные, названия объектов и организаций
- сокращать реплику до пересказа/резюме — переписываешь КАЖДУЮ мысль, а не выбираешь главную
- отвечать за спикера тем, что он не говорил, даже если "напрашивается"

ФОРМАТ ОТВЕТА — СТРОГО построчно, без пояснений, без JSON:
[номер] переписанный текст реплики
Сохрани все номера. Каждая входная реплика = ровно одна строка ответа с тем же номером.
Имя/роль спикера в начале строки в ответ НЕ включай — они уже известны читателю.${glossaryBlock}`;

  const user = `${contextBlock}Реплики (уже с корректными терминами и числами):
${numberedLines.join("\n")}

Верни литературную запись построчно в формате [номер] текст.`;

  // Выход обычно короче входа (убрали филлеры) — бюджет как у входа, без запаса на раздувание
  const inputChars = numberedLines.reduce((s, l) => s + l.length, 0);
  const maxTokens = Math.min(8000, Math.max(1000, Math.ceil(inputChars / 2.5)));

  return { system, user, options: { temperature: 0.3, maxTokens } };
}

